  // =========================================================
  // Traducción
  // =========================================================
  function getLang() {
    if (window._afI18n && window._afI18n.currentLang) return window._afI18n.currentLang();
    try { return localStorage.getItem('af:lang') || 'es'; } catch (e) { return 'es'; }
  }

  function normalize(s) {
    if (typeof s !== 'string') return s;
    return s.replace(/\u2212/g, '−').trim();
  }

  function t(key, lang) {
    lang = lang || getLang();
    if (STRINGS[lang] && STRINGS[lang][key]) return STRINGS[lang][key];
    if (STRINGS.es && STRINGS.es[key]) return STRINGS.es[key];
    return key;
  }

  function format(str, args) {
    if (!str) return '';
    return str.replace(/\{(\d+)\}/g, function (_, i) {
      return args[parseInt(i, 10)] != null ? String(args[parseInt(i, 10)]) : '';
    });
  }

  // Traduce cualquier string generado por los cores
  function translate(str, lang) {
    if (str == null) return str;
    if (typeof str !== 'string') str = String(str);
    lang = lang || getLang();
    if (lang === 'es') return str;

    var s = str.trim();
    if (!s) return str;

    // 1) Match exacto en STRINGS
    if (STRINGS[lang] && STRINGS[lang]['val.' + s])
      return STRINGS[lang]['val.' + s];
    if (STRINGS[lang] && STRINGS[lang]['pt.' + s])
      return STRINGS[lang]['pt.' + s];

    // 2) Patrones
    for (var i = 0; i < PATTERNS.length; i++) {
      var p = PATTERNS[i];
      var m = s.match(p.re);
      if (m) {
        var rule = p[lang];
        if (typeof rule === 'function') return rule(m);
        if (typeof rule === 'string') return rule;
      }
    }

    // 3) Nada coincide → devolver tal cual
    return str;
  }

  // =========================================================
  // API
  // =========================================================
  window._afI18nFull = {
    strings: STRINGS,
    patterns: PATTERNS,
    t: t,
    format: format,
    translate: translate,
    currentLang: getLang
  };
